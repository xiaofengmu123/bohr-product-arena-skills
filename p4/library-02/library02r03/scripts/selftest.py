"""selftest.py - deterministic self-check for the document library skill.

Creates a fixed, reproducible fixture under a temp directory, runs the full
pipeline twice into two separate output/work trees, then verifies:

1. both runs succeed (exit code 0);
2. result.json is deep-equal after stripping explicitly volatile keys
   (generated_at / time / runtime seconds) -- i.e. determinism;
3. every non-result artifact is byte-identical across the two runs;
4. --check passes on the produced result.json;
5. the output contract fields and required metadata fields are present.

Only the standard library is used. The fixture is generated by this script
itself (never shipped as a "formal answer"), so no prepared case answers exist
in the package.
"""
import argparse
import json
import os
import shutil
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
if HERE not in sys.path:
    sys.path.insert(0, HERE)

import core_impl  # noqa: E402

VOLATILE_KEYS = {"generated_at", "time", "seconds", "started_at", "finished_at",
                 "duration", "wall_time", "mtime", "output_dir", "work_dir"}

REQUIRED_TOP = ("case_id", "status", "sources", "uncertainty", "change_log",
                "errors", "degradations", "runtime", "limitations", "computed")

ARTIFACTS = ("library_manifest.csv", "directory_tree.txt", "dedup_version.json",
             "recovery_report.json", "library_index.json",
             "library_manifest.md", "operation_log.jsonl")


def strip_volatile(obj):
    if isinstance(obj, dict):
        return {k: strip_volatile(v) for k, v in obj.items() if k not in VOLATILE_KEYS}
    if isinstance(obj, list):
        return [strip_volatile(v) for v in obj]
    return obj


def write_fixture(root):
    """Build a deterministic fixture. Returns dict with expectations."""
    files = {}
    os.makedirs(os.path.join(root, "materials", "project_a"), exist_ok=True)
    os.makedirs(os.path.join(root, "materials", "empty_dir"), exist_ok=True)

    def w(rel, content, mode="t"):
        p = os.path.join(root, rel)
        os.makedirs(os.path.dirname(p), exist_ok=True)
        if mode == "b":
            with open(p, "wb") as fh:
                fh.write(content)
        else:
            with open(p, "w", encoding="utf-8") as fh:
                fh.write(content)
        return p

    # two identical copies -> duplicate group
    w("materials/project_a/notes.txt",
      "buffer recipe: 20 mM Tris-HCl, pH 7.4, 150 mM NaCl.\n")
    w("materials/project_a/notes-copy.txt",
      "buffer recipe: 20 mM Tris-HCl, pH 7.4, 150 mM NaCl.\n")
    # two versions -> version candidate
    w("materials/project_a/protocol_v1.txt",
      "Protocol for cell lysis. Step 1: add RIPA buffer. Step 2: incubate 30 min.\n")
    w("materials/project_a/protocol_v2.txt",
      "Protocol for cell lysis. Step 1: add RIPA buffer. Step 2: incubate 45 min.\n")
    # a manifest declaring one path with a correct hash and one missing path
    import hashlib
    h = hashlib.sha256(b"buffer recipe: 20 mM Tris-HCl, pH 7.4, 150 mM NaCl.\n").hexdigest()
    w("materials/library_manifest.json", json.dumps({
        "files": [
            {"path": "materials/project_a/notes.txt", "sha256": h, "version": "1"},
            {"path": "materials/project_a/gone.txt", "sha256": "0" * 64},
        ]
    }, sort_keys=True))
    # a broken JSON file -> degrade but not crash
    w("materials/bad.json", "{ this is not valid json")
    # an unreadable-style large file is not created here (cross-platform); the
    # too_large path is exercised by unit-style assertion in checklist only.
    w("materials/project_a/data.bin", b"\x00\x01\x02\x03", mode="b")

    # symlink (best-effort; Windows may lack privilege)
    try:
        os.symlink(os.path.join(root, "materials", "project_a", "notes.txt"),
                   os.path.join(root, "materials", "alias_notes.txt"))
    except (OSError, NotImplementedError):
        pass

    return files


def run_once(core_argv, out, work):
    argv = list(core_argv) + ["--output", out, "--work", work]
    return core_impl.main(argv)


def deep_equal(a, b, path="$"):
    if type(a) is not type(b):
        return False, f"{path}: type mismatch {type(a).__name__} vs {type(b).__name__}"
    if isinstance(a, dict):
        if set(a.keys()) != set(b.keys()):
            return False, f"{path}: key set mismatch {set(a) ^ set(b)}"
        for k in a:
            ok, msg = deep_equal(a[k], b[k], f"{path}.{k}")
            if not ok:
                return False, msg
        return True, ""
    if isinstance(a, list):
        if len(a) != len(b):
            return False, f"{path}: length mismatch {len(a)} vs {len(b)}"
        for i, (x, y) in enumerate(zip(a, b)):
            ok, msg = deep_equal(x, y, f"{path}[{i}]")
            if not ok:
                return False, msg
        return True, ""
    return (a == b, f"{path}: {a!r} != {b!r}" if a != b else "")


def main(argv=None):
    ap = argparse.ArgumentParser(prog="selftest.py")
    ap.add_argument("--input", default=None, help="optional: run against this dir instead of fixture")
    ap.add_argument("--case-json", default=None)
    ap.add_argument("--task-path", default=None)
    args = ap.parse_args(argv)

    tmp = tempfile.mkdtemp(prefix="lib-selftest-")
    failures = []

    try:
        if args.input:
            input_root = args.input
        else:
            input_root = os.path.join(tmp, "input")
            os.makedirs(input_root, exist_ok=True)
            write_fixture(input_root)

        base_argv = ["--input", input_root]
        if args.case_json:
            base_argv += ["--case-json", args.case_json]
        if args.task_path:
            base_argv += ["--task-path", args.task_path]

        out1 = os.path.join(tmp, "out1")
        out2 = os.path.join(tmp, "out2")
        work1 = os.path.join(tmp, "work1")
        work2 = os.path.join(tmp, "work2")

        rc1 = run_once(base_argv, out1, work1)
        rc2 = run_once(base_argv, out2, work2)
        if rc1 != 0 or rc2 != 0:
            failures.append(f"pipeline exit codes: run1={rc1}, run2={rc2}")

        r1 = json.load(open(os.path.join(out1, "result.json"), encoding="utf-8"))
        r2 = json.load(open(os.path.join(out2, "result.json"), encoding="utf-8"))

        # determinism (strip volatile keys)
        s1, s2 = strip_volatile(r1), strip_volatile(r2)
        ok, msg = deep_equal(s1, s2)
        if not ok:
            failures.append(f"determinism: {msg}")

        # artifact byte-identity
        for a in ARTIFACTS:
            p1, p2 = os.path.join(out1, a), os.path.join(out2, a)
            if not os.path.exists(p1) or not os.path.exists(p2):
                failures.append(f"artifact missing across runs: {a}")
                continue
            b1 = open(p1, "rb").read()
            b2 = open(p2, "rb").read()
            if b1 != b2:
                failures.append(f"artifact not byte-identical: {a}")

        # required top-level fields
        for f in REQUIRED_TOP:
            if f not in r1:
                failures.append(f"result.json missing field: {f}")

        # contract backfill: fixture has no case.json, so check metadata path
        if not r1.get("case_id"):
            failures.append("case_id empty in selftest result")

        # --check must pass
        rc = core_impl.main(["--check", os.path.join(out1, "result.json")])
        if rc != 0:
            failures.append(f"--check returned {rc}")

        # summary sanity (fixture has 1 duplicate group and >=1 version candidate)
        summary = r1.get("computed", {}).get("summary", {})
        if summary.get("duplicate_groups", 0) < 1:
            failures.append(f"expected >=1 duplicate group, got {summary.get('duplicate_groups')}")
        if summary.get("version_candidate_groups", 0) < 1:
            failures.append(f"expected >=1 version candidate group, got {summary.get('version_candidate_groups')}")

    except Exception as exc:  # a self-test crash is itself a failure
        failures.append(f"selftest crashed: {type(exc).__name__}: {exc}")
    finally:
        shutil.rmtree(tmp, ignore_errors=True)

    if failures:
        print("SELFTEST FAIL")
        for f in failures:
            print("  - " + f)
        return 1
    print("SELFTEST PASS: determinism + artifacts + check all verified")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
